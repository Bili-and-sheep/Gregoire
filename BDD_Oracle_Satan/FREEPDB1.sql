-- Players + squads: 35 per team
DECLARE
  CURSOR c_team IS SELECT id_equipe, id_pays FROM rwc_equipes;
  v_pid NUMBER;
BEGIN
  FOR tm IN c_team LOOP
    FOR i IN 1..35 LOOP
      INSERT INTO rwc_joueurs(id_pays, joueur_nom, joueur_dt_naiss)
      VALUES (
        tm.id_pays,
        'Player '||tm.id_equipe||'-'||LPAD(i,2,'0'),
        DATE '1988-01-01' + TRUNC(DBMS_RANDOM.VALUE(0, 5000))
      )
      RETURNING id_joueur INTO v_pid;

      INSERT INTO rwc_postes(id_equipe, id_joueur, poste_num_maillot, poste_position_code)
      VALUES (
        tm.id_equipe,
        v_pid,
        i,
        CASE
          WHEN i = 1 THEN 'LH'
          WHEN i = 2 THEN 'HK'
          WHEN i = 3 THEN 'TH'
          WHEN i IN (4,5) THEN 'LK'
          WHEN i IN (6,7) THEN 'FL'
          WHEN i = 8 THEN 'N8'
          WHEN i = 9 THEN 'SH'
          WHEN i = 10 THEN 'FH'
          WHEN i = 11 THEN 'LC'
          WHEN i = 12 THEN 'IC'
          WHEN i = 13 THEN 'RW'
          WHEN i = 14 THEN 'LW'
          WHEN i = 15 THEN 'FB'
          ELSE 'RES'
        END
      );
    END LOOP;
  END LOOP;
END;
/
COMMIT;

-- Fans: 1000
DECLARE
BEGIN
  FOR i IN 1..1000 LOOP
    INSERT INTO rwc_fans(id_pays, fan_nom, fan_email)
    VALUES (
      (SELECT id_pays FROM rwc_pays ORDER BY DBMS_RANDOM.VALUE FETCH FIRST 1 ROWS ONLY),
      'Fan '||LPAD(i,5,'0'),
      'fan'||LPAD(i,5,'0')||'@example.org'
    );
  END LOOP;
END;
/
COMMIT;

-- Tickets: 10000
DECLARE
BEGIN
  FOR i IN 1..10000 LOOP
    INSERT INTO rwc_tickets(id_match, id_fan, ticket_cat, ticket_prix)
    VALUES (
      (SELECT id_match FROM rwc_matchs ORDER BY DBMS_RANDOM.VALUE FETCH FIRST 1 ROWS ONLY),
      (SELECT id_fan   FROM rwc_fans   ORDER BY DBMS_RANDOM.VALUE FETCH FIRST 1 ROWS ONLY),
      CASE
        WHEN MOD(i,25)=0 THEN 'VIP'
        WHEN MOD(i,3)=0  THEN 'CAT1'
        WHEN MOD(i,3)=1  THEN 'CAT2'
        ELSE 'CAT3'
      END,
      CASE
        WHEN MOD(i,25)=0 THEN 500
        WHEN MOD(i,3)=0  THEN 180
        WHEN MOD(i,3)=1  THEN 120
        ELSE 70
      END
    );
  END LOOP;
END;
