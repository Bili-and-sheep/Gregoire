-- 8) Promote staging -> normalized match tables
-- FIX: avoid calling local PL/SQL functions from SQL (PLS-00231).
--------------------------------------------------------------------------------
DECLARE
  v_tid     NUMBER;

  v_mid     NUMBER;
  v_venue   NUMBER;
  v_pool    NUMBER;
  v_home    NUMBER;
  v_away    NUMBER;

  v_kick_ts TIMESTAMP;
BEGIN
  SELECT id_tournoi INTO v_tid
  FROM rwc_tournois
  WHERE tournoi_edition = 2023;

  FOR r IN (SELECT * FROM rwc_matchs_stg ORDER BY match_date, match_code) LOOP

    --------------------------------------------------------------------------
    -- 1) Resolve lookup keys -> surrogate keys (IDs)
    --------------------------------------------------------------------------

    -- Venue from match_ville
    SELECT id_stade INTO v_venue
    FROM rwc_stades
    WHERE stade_ville = r.match_ville;

    -- Pool from poule_code (nullable for knockout)
    IF r.poule_code IS NOT NULL THEN
      SELECT id_poule INTO v_pool
      FROM rwc_poules
      WHERE id_tournoi = v_tid
        AND poule_code = r.poule_code;
    ELSE
      v_pool := NULL;
    END IF;

    -- Teams from names
    SELECT id_equipe INTO v_home
    FROM rwc_equipes
    WHERE id_tournoi = v_tid
      AND equipe_lib = r.match_equipe_locale;

    SELECT id_equipe INTO v_away
    FROM rwc_equipes
    WHERE id_tournoi = v_tid
      AND equipe_lib = r.match_equipe_visiteur;

    --------------------------------------------------------------------------
    -- 2) Build kickoff timestamp only when provided (no guessing)
    --------------------------------------------------------------------------
    IF r.match_heure_kickoff IS NOT NULL THEN
      v_kick_ts := TO_TIMESTAMP(
        TO_CHAR(r.match_date,'YYYY-MM-DD') || ' ' || r.match_heure_kickoff,
        'YYYY-MM-DD HH24:MI'
      );
    ELSE
      v_kick_ts := NULL;
    END IF;

    --------------------------------------------------------------------------
    -- 3) Insert match + the 2 result lines (HOME / AWAY)
    --------------------------------------------------------------------------
    INSERT INTO rwc_matchs(id_tournoi, id_stade, match_tour, id_poule, match_date, match_kickoff, match_code)
    VALUES (v_tid, v_venue, r.match_tour, v_pool, r.match_date, v_kick_ts, r.match_code)
    RETURNING id_match INTO v_mid;

    INSERT INTO rwc_resultats(id_match, id_equipe, resultat_side, resultat_points)
    VALUES (v_mid, v_home, 'HOME', r.match_equipe_locale_pts);

    INSERT INTO rwc_resultats(id_match, id_equipe, resultat_side, resultat_points)
    VALUES (v_mid, v_away, 'AWAY', r.match_equipe_visiteur_pts);

  END LOOP;
END;
/
COMMIT;

