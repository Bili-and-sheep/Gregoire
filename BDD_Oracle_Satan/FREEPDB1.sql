-- Players are stored by nationality (id_pays). Names here are synthetic by default.
CREATE TABLE rwc_joueurs (
  id_joueur			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pays			NUMBER			NOT NULL REFERENCES rwc_pays(id_pays),
  joueur_nom		VARCHAR2(120)	NOT NULL,
  joueur_dt_naiss	DATE
);

-- Squad membership for the tournament (one row per player per team + shirt number)
CREATE TABLE rwc_postes (
  id_poste			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  poste_num_maillot	NUMBER(2)		NOT NULL,
  poste_position_code VARCHAR2(3)	NOT NULL,
  id_equipe			NUMBER			NOT NULL REFERENCES rwc_equipes(id_equipe),
  id_joueur			NUMBER			NOT NULL REFERENCES rwc_joueurs(id_joueur),
  CONSTRAINT rwc_postes_uk UNIQUE (id_equipe, id_joueur),
  CONSTRAINT rwc_postes_num_uk UNIQUE (id_equipe, poste_num_maillot)
);

-- Fans
CREATE TABLE rwc_fans (
  id_fan			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fan_nom			VARCHAR2(120)	NOT NULL,
  fan_email			VARCHAR2(200)	NOT NULL UNIQUE,
  fan_dt_crea		TIMESTAMP		DEFAULT SYSTIMESTAMP NOT NULL,
  id_pays			NUMBER			REFERENCES rwc_pays(id_pays)
);

-- Tickets (high-volume table for GROUP BY, joins, top-N, window functions, etc.)
CREATE TABLE rwc_tickets (
  id_ticket			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_cat		VARCHAR2(10)	NOT NULL CHECK (ticket_cat IN ('CAT1','CAT2','CAT3','VIP')),
  ticket_prix		NUMBER(7,2)		NOT NULL CHECK (ticket_prix > 0),
  ticket_dt_achat	TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  id_match			NUMBER			NOT NULL REFERENCES rwc_matchs(id_match) ON DELETE CASCADE,
  id_fan			NUMBER			NOT NULL REFERENCES rwc_fans(id_fan) ON DELETE CASCADE
);

CREATE INDEX ix_ticket_match ON rwc_tickets(id_match);
CREATE INDEX ix_ticket_fan   ON rwc_tickets(id_fan);

