--------------------------------------------------------------------------------
-- 2) Core reference tables (PAYS, TOURNOIS, POULES, EQUIPES, STADES)
--------------------------------------------------------------------------------

-- Countries participating in RWC 2023 (20 teams)
CREATE TABLE rwc_pays (
  id_pays			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pays_iso_code		CHAR(3)			NOT NULL UNIQUE,
  pays_nom			VARCHAR2(80)	NOT NULL
);

-- Tournament header (host country, dates, edition year)
CREATE TABLE rwc_tournois (
  id_tournoi		NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournoi_lib		VARCHAR2(120)	NOT NULL,
  tournoi_dt_deb	DATE			NOT NULL,
  tournoi_dt_fin	DATE			NOT NULL,
  tournoi_edition	NUMBER(4)		NOT NULL,
  id_pays			NUMBER			NOT NULL REFERENCES rwc_pays(id_pays),
  CONSTRAINT rwc_tourn_dates_ck CHECK (tournoi_dt_fin >= tournoi_dt_deb)
);

-- Pools A-D (per tournament)
CREATE TABLE rwc_poules (
  id_poule			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  poule_code		CHAR(1)			NOT NULL,
  id_tournoi		NUMBER			NOT NULL REFERENCES rwc_tournois(id_tournoi),
  CONSTRAINT rwc_poules_uk UNIQUE (id_tournoi, poule_code),
  CONSTRAINT rwc_poules_code_ck CHECK (poule_code IN ('A','B','C','D'))
);

-- Teams (one per country per tournament; attached to a pool)
CREATE TABLE rwc_equipes (
  id_equipe			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipe_lib		VARCHAR2(80)	NOT NULL,
  id_pays			NUMBER			NOT NULL REFERENCES rwc_pays(id_pays),
  id_tournoi		NUMBER			NOT NULL REFERENCES rwc_tournois(id_tournoi),
  id_poule			NUMBER			NOT NULL REFERENCES rwc_poules(id_poule),
  CONSTRAINT rwc_equipes_uk UNIQUE (id_tournoi, id_pays)
);

-- Venues (official host cities; match_ville is unique for simple mapping)
CREATE TABLE rwc_stades (
  id_stade			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stade_ville		VARCHAR2(80)	NOT NULL UNIQUE,
  stade_lib			VARCHAR2(120)	NOT NULL,
  stade_capacite	NUMBER(7)		NOT NULL,
  id_tournoi		NUMBER			NOT NULL REFERENCES rwc_tournois(id_tournoi),
  CONSTRAINT rwc_stades_cap_ck CHECK (stade_capacite > 0)
);

--------------------------------------------------------------------------------
-- 3) Matches & results tables
--------------------------------------------------------------------------------

-- Matches (we store match_date for accuracy; match_kickoff kept nullable by design)
CREATE TABLE rwc_matchs (
  id_match			NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_tour		VARCHAR2(20)	NOT NULL CHECK (match_tour IN ('POOL','QF','SF','FINAL','BRONZE')),
  match_date		DATE			NOT NULL,
  match_kickoff		TIMESTAMP		NULL,
  match_code		VARCHAR2(30)	NOT NULL,
  match_recette		NUMBER(12,2)	NULL,
  id_tournoi		NUMBER			NOT NULL REFERENCES rwc_tournois(id_tournoi),
  id_stade			NUMBER			NOT NULL REFERENCES rwc_stades(id_stade),
  id_poule			NUMBER			NULL REFERENCES rwc_poules(id_poule),
  CONSTRAINT rwc_matchs_uk UNIQUE (id_tournoi, match_code)
);

-- Match results: two lines per match (HOME/AWAY)
CREATE TABLE rwc_resultats (
  id_resultat		NUMBER			GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resultat_side		VARCHAR2(4)		NOT NULL CHECK (resultat_side IN ('HOME','AWAY')),
  resultat_points	NUMBER(3)		NOT NULL,
  id_match			NUMBER			NOT NULL REFERENCES rwc_matchs(id_match) ON DELETE CASCADE,
  id_equipe			NUMBER			NOT NULL REFERENCES rwc_equipes(id_equipe),
  CONSTRAINT rwc_resultats_uk UNIQUE (id_match, resultat_side),
  CONSTRAINT rwc_resultats_uk2 UNIQUE (id_match, id_equipe)
);

-- Helpful indexes for the future exercises
CREATE INDEX ix_match_date			ON rwc_matchs(match_date);
CREATE INDEX ix_match_match_tour	ON rwc_matchs(match_tour);
CREATE INDEX ix_matchteam_mid		ON rwc_resultats(id_match);

